/**
 * Refreshes src/copy/registryScaleData.js from the live stats endpoint, so the
 * scale figures quoted on the landing page, the FAQ, the FAQPage JSON-LD and
 * llms.txt track the index instead of being retyped by hand.
 *
 * Two rules, both deliberate:
 *
 *   - A failure NEVER breaks the build. The committed values ship instead. A
 *     stale number is a small problem; a site that will not deploy because a
 *     stats endpoint blinked is a large one.
 *   - A number is only accepted if it is plausible. A blue/green index rebuild
 *     can leave the alias pointing at a half-populated index, and publishing
 *     "1.2 million companies" off the back of that would be worse than
 *     publishing yesterday's correct figure.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REGISTRY_SCALE_RAW } from '../src/copy/registryScaleData.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.resolve(__dirname, '..', 'src', 'copy', 'registryScaleData.js');
const llmsFile = path.resolve(__dirname, '..', 'public', 'llms.txt');
const indexHtmlFile = path.resolve(__dirname, '..', 'index.html');

const STATS_URL = `${process.env.VITE_API_URL || 'https://api.ncdata.eu'}/bormes/stats/overview`;
const TIMEOUT_MS = 15_000;

/**
 * A rebuild in flight can leave the alias on a partially populated index.
 * Anything below this share of the last known figure is treated as a bad read.
 */
const MIN_PLAUSIBLE_RATIO = 0.9;

/** endpoint field -> the key we store it under */
const FIELDS = {
  total_companies: 'totalCompanies',
  total_events: 'totalEvents',
  officer_changes: 'officerChanges',
  constitutions: 'constitutions',
};

const warn = message => console.warn(`[registry-scale] ${message} — keeping committed values.`);

async function fetchOverview() {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const resp = await fetch(STATS_URL, { signal: controller.signal });
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    const body = await resp.json();
    if (!body?.success) throw new Error(body?.error || 'success flag not set');
    return body;
  } finally {
    clearTimeout(timer);
  }
}

/**
 * @returns {Record<string, number>|null} accepted values, or null if any field
 * is missing or implausible. All-or-nothing: a mix of fresh and stale figures
 * across one sentence is harder to reason about than a wholly stale one.
 */
function validate(body) {
  const next = {};
  for (const [field, key] of Object.entries(FIELDS)) {
    const value = body[field];
    if (!Number.isInteger(value) || value <= 0) {
      warn(`${field} is not a positive integer (${JSON.stringify(value)})`);
      return null;
    }
    const floor = REGISTRY_SCALE_RAW[key] * MIN_PLAUSIBLE_RATIO;
    if (value < floor) {
      warn(`${field} came back ${value.toLocaleString()}, below ${Math.round(floor).toLocaleString()} (index rebuild?)`);
      return null;
    }
    next[key] = value;
  }
  return next;
}

const serialise = values => `/**
 * GENERATED by scripts/generate-registry-scale.mjs — do not edit by hand.
 *
 * Committed values are the build's fallback: if the stats endpoint is
 * unreachable at build time the site ships these rather than failing, so the
 * numbers can only ever be stale, never absent or wrong-by-typo.
 */
export const REGISTRY_SCALE_RAW = {
${Object.entries(values).map(([k, v]) => `  ${k}: ${v},`).join('\n')}
};
`;

/**
 * llms.txt is prose maintained by hand; only the two figures in its summary
 * line are owned here. Rewritten in place so the file stays readable and
 * reviewable rather than becoming another generated artefact.
 */
const oneDecimal = n => (Math.round(n / 100_000) / 10).toFixed(1);

/**
 * Rewrite one figure inside a prose file. Returns the updated text, and warns
 * if the pattern no longer matches — a silently-skipped replacement is how the
 * numbers drifted apart in the first place.
 */
function rewrite(text, pattern, replacement, label) {
  if (!pattern.test(text)) {
    warn(`${label} no longer matches the expected shape`);
    return text;
  }
  return text.replace(pattern, replacement);
}

/**
 * These files are hand-maintained prose; only their figures are owned here, so
 * they stay readable and reviewable rather than becoming generated artefacts.
 *
 * Runs on EVERY build, not only when the live number moves: a file that has
 * drifted by hand must be corrected on the next build, not left until the
 * index happens to change.
 */
function syncProse(values) {
  const companies = oneDecimal(values.totalCompanies);
  const filings = oneDecimal(values.totalEvents);

  const llmsBefore = readFileSync(llmsFile, 'utf8');
  const llmsAfter = rewrite(
    llmsBefore,
    /~[\d.]+M companies and ~[\d.]+M filings/,
    `~${companies}M companies and ~${filings}M filings`,
    'llms.txt summary line'
  );
  if (llmsAfter !== llmsBefore) {
    writeFileSync(llmsFile, llmsAfter);
    console.log('[registry-scale] llms.txt updated');
  }

  // Site-wide JSON-LD descriptions in the Vite entry template, which prerender
  // copies into every generated page.
  const htmlBefore = readFileSync(indexHtmlFile, 'utf8');
  let htmlAfter = rewrite(
    htmlBefore,
    /covering [\d.]+ million companies since 2009/,
    `covering ${companies} million companies since 2009`,
    'index.html company description'
  );
  htmlAfter = rewrite(
    htmlAfter,
    /built on [\d.]+ million official BORME publication records/,
    `built on ${filings} million official BORME publication records`,
    'index.html filings description'
  );
  if (htmlAfter !== htmlBefore) {
    writeFileSync(indexHtmlFile, htmlAfter);
    console.log('[registry-scale] index.html JSON-LD updated');
  }
}

async function main() {
  let fetched = null;
  try {
    fetched = validate(await fetchOverview());
  } catch (err) {
    warn(`could not read ${STATS_URL} (${err.message})`);
  }

  // Fall back to the committed figures so the prose files are still brought
  // into line with whatever the app is actually about to ship.
  const values = fetched || REGISTRY_SCALE_RAW;

  if (fetched && Object.entries(fetched).some(([k, v]) => REGISTRY_SCALE_RAW[k] !== v)) {
    writeFileSync(dataFile, serialise(fetched));
    console.log(
      `[registry-scale] refreshed: ${fetched.totalCompanies.toLocaleString()} companies, ` +
      `${fetched.totalEvents.toLocaleString()} filings`
    );
  } else if (fetched) {
    console.log('[registry-scale] already current');
  }

  syncProse(values);
}

main().catch(err => warn(`unexpected failure (${err.message})`));
