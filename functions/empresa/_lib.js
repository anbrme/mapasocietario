export async function handleCompany({ params, env }, lang = 'es') {
  const slug = String(params.slug || '').toLowerCase();
  const resolved = resolveSlug(slug);
  // A demand-promoted company is resolved by its stable group_key and becomes
  // indexable without being hard-coded in CURATED. When D1 is absent or a row
  // is not promoted, the existing safe noindex fallback remains unchanged.
  const promoted = resolved.kind === 'notfound'
    ? await findPromotedCompanyBySlug(env?.SEO_DB, slug)
    : null;
  const isFallback = resolved.kind === 'notfound' && !promoted;
  const seed = resolved.kind === 'seed' ? resolved.entry : null;
  let name = promoted?.canonical_name || (isFallback ? slugToQuery(slug) : resolved.entry.v3Name);

  // Seed companies resolve by registry identity (hoja → group_key), not by
  // name: enrichment runs can re-canonicalize a doc's name (e.g. "INDUSTRIA DE
  // DISEÑO TEXTIL, S.A.(R.M. A CORUÑA)" → "...S.A."), and by-name lookups can
  // collide with smaller same-named docs (BANKINTER SA exists on 3 hojas). The
  // hoja never changes, so these indexed pages survive both.
  const groupKey = promoted?.group_key || (seed && seed.hoja ? hojaGroupKey(seed.hoja) : null);

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 10000);

  try {
    // BOE mentions match by company name + NIF (listed cos have both in the seed).
    const boeUrl = seed
      ? `${API_BASE}/bormes/boe/company-mentions?name=${encodeURIComponent(seed.name || '')}&nif=${encodeURIComponent(seed.nif || '')}&categories=sancion,subvencion,contrato&size=8`
      : null;
    let [profile, eventsResp, cnmvResp, chartSvg, boeResp, gleifResp] = await Promise.all([
      jsonOrNull(
        groupKey
          ? `${API_BASE}/bormes/v3/company?group_key=${encodeURIComponent(groupKey)}`
          : `${API_BASE}/bormes/v3/company/${encodeURIComponent(name)}`,
        controller.signal,
      ),
      // Fetch enough history to group publications by year and paginate them
      // inside the page without a second browser request.
      jsonOrNull(
        groupKey
          ? `${API_BASE}/bormes/v3/events?group_key=${encodeURIComponent(groupKey)}&size=100`
          : `${API_BASE}/bormes/v3/events?company=${encodeURIComponent(name)}&size=100`,
        controller.signal,
      ),
      // Significant shareholders + history chart: only IBEX seed companies have CNMV data.
      seed ? jsonOrNull(`${API_BASE}/bormes/cnmv/shareholders?company=${encodeURIComponent(slug)}`, controller.signal) : Promise.resolve(null),
      seed ? textOrNull(`${API_BASE}/bormes/cnmv/history-chart?company=${encodeURIComponent(slug)}&lang=${lang}`, controller.signal) : Promise.resolve(null),
      boeUrl ? jsonOrNull(boeUrl, controller.signal) : Promise.resolve(null),
      // GLEIF corporate group: only IBEX seed companies carry a verified LEI.
      seed && seed.lei
        ? postJsonOrNull(`${API_BASE}/lei-relationships`, { lei: seed.lei, isPublic: true }, controller.signal)
        : Promise.resolve(null),
    ]);

    let company = profile && profile.company ? profile.company : null;

    // Seed rescue: if the group_key lookup ever fails (endpoint outage, hoja
    // re-keyed), retry the stored v3Name so the indexed page degrades to the
    // old behaviour instead of 404ing.
    if (!company && groupKey) {
      const byName = await jsonOrNull(
        `${API_BASE}/bormes/v3/company/${encodeURIComponent(name)}`,
        controller.signal,
      );
      if (byName && byName.company) company = byName.company;
    }

    // Fallback rescue: the exact name lookup above can't reverse lossy slug
    // substitutions (nameToSlug turns "&"→"y" and "ñ"→"n"), so companies like
    // "NURNBERG CONSULTING & PARTNERS SL" or "...MUÑOZ..." miss. Resolve the
    // canonical name via search (tokenized) and re-fetch. pickSlugMatch keeps it
    // exact (only a hit whose slug === the requested slug is accepted), and the
    // round-trip guard below is the final safety net.
    if (isFallback && (!company || nameToSlug(company.company_name) !== slug)) {
      const searchResp = await jsonOrNull(
        `${API_BASE}/bormes/v3/search?query=${encodeURIComponent(name)}&size=10`,
        controller.signal,
      );
      const canonical = pickSlugMatch(
        slug,
        (searchResp && (searchResp.companies || searchResp.results || searchResp.hits)) || [],
      );
      if (canonical) {
        const [p2, e2] = await Promise.all([
          jsonOrNull(`${API_BASE}/bormes/v3/company/${encodeURIComponent(canonical)}`, controller.signal),
          jsonOrNull(`${API_BASE}/bormes/v3/events?company=${encodeURIComponent(canonical)}&size=100`, controller.signal),
        ]);
        if (p2 && p2.company) {
          company = p2.company;
          eventsResp = e2;
          name = canonical;
        }
      }
    }

    if (!company) {
      // Cache only fallback misses (garbage slugs). For a curated/IBEX slug a
      // missing company is most likely a TRANSIENT backend failure on an
      // indexed page — never cache that, or a blip would pin a 404 for 10 min.
      return new Response(notFoundPage(slug, lang), {
        status: 404,
        headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': isFallback ? 'public, s-maxage=600' : 'no-store' },
      });
    }

    // Fallback pages must round-trip exactly: the canonical name's slug has to
    // equal the requested slug, or we'd serve the wrong (lossy-matched) entity.
    if (isFallback && nameToSlug(company.company_name) !== slug) {
      return new Response(notFoundPage(slug, lang), {
        status: 404,
        headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, s-maxage=600' },
      });
    }

    // The events endpoint falls back to name matching, which can leak events of
    // OTHER companies whose name embeds this one (e.g. an AIE named after its
    // members). Keep only events whose group_key belongs to this company; events
    // without a group_key pass (fail open — never blank the section).
    const allowed = new Set(
      [
        company._id,
        ...(company.hojas || []).map((h) => `H:${h}`),
        company.company_name_normalized ? `N:${company.company_name_normalized}` : null,
      ].filter(Boolean)
    );
    const events = ((eventsResp && eventsResp.events) || [])
      .filter((e) => !e.group_key || allowed.has(e.group_key))
      .slice(0, 100);

    // A promoted page is indexable, so it has to keep round-tripping too. If the
    // company was renamed after promotion its live name no longer matches this
    // slug, and asserting the page as canonical would point Google at a stale
    // identity. Keep serving it (it may already be indexed) but drop it out of
    // the index; the next demand signal re-validates and demotes the D1 row.
    const staleSlug = Boolean(promoted) && nameToSlug(company.company_name) !== slug;
    const noindex = isFallback || staleSlug;

    const gleif = gleifResp && gleifResp.success ? gleifResp.data : null;
    const html = renderCompanyPage(company, events, slug, seed, lang, cnmvResp, sanitizeSvg(chartSvg), boeResp, gleif, noindex);
    return new Response(html, {
      status: 200,
      headers: {
        'content-type': 'text/html; charset=utf-8',
        // One hour, not one day. The registry publishes daily and the officer
        // tables above are rendered from it: a 24h edge cache could keep serving
        // a board that changed this morning long after the backend knew. At this
        // traffic a page re-renders at most 24 times a day, which is nothing.
        // stale-while-revalidate is kept for origin trouble, but bounded to a
        // day so a rarely-visited page cannot serve a week-old board.
        'cache-control': noindex
          ? 'public, max-age=0, s-maxage=600'
          : 'public, max-age=0, s-maxage=3600, stale-while-revalidate=86400',
      },
    });
  } catch {
    return new Response(notFoundPage(slug, lang), {
      status: 503,
      headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' },
    });
  } finally {
    clearTimeout(timeout);
  }
}

