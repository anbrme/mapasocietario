const MAX_OFFICERS = 40;

// Company-level governing-organ categories shown under "Administradores y cargos
// vigentes". Everything else (Apoderado, Auditor, Vocal / Comisión, Otros) is a
// non-board role. Classification is delegated to the shared positionCategoryFor
// so the page and the graph never diverge on a position string.
const BOARD_CATEGORIES = new Set([
  'Presidente',
  'Vicepresidente',
  'Consejero',
  'Administrador',
  'Representante 143 RRM',
  'Secretario',
  'Liquidador',
]);

function isBoardRole(o) {
  return BOARD_CATEGORIES.has(positionCategoryFor(o.position_normalized || o.position || ''));
}

function prettyPosition(pos, t) {
  const p = (pos || '').toUpperCase();
  return t.positions[p] || pos || '';
}

function selectOfficers(list) {
  const all = list || [];
  const board = all.filter(isBoardRole);
  const shown = board.slice(0, MAX_OFFICERS);
  const omitted = [...board.slice(MAX_OFFICERS), ...all.filter((officer) => !isBoardRole(officer))];
  return { shown, omitted };
}

function officersRows(rawList, dateKey, dateLabel, t, lang, { noBoardNote = false } = {}) {
  const { shown: list, omitted } = selectOfficers(rawList);
  if (!list.length && !omitted.length) return '';
  const renderRows = (officers) => officers
    .map(
      (o) => `<tr>
        <td>${esc(o.name || o.name_normalized)}${o.ceased_as ? ` <span class="muted">(${esc(t.ceasedAs(o.ceased_as))})</span>` : ''}</td>
        <td>${esc(prettyPosition(o.position_normalized || o.position, t))}</td>
        <td>${esc(fmtDate(o[dateKey], lang))}</td>
      </tr>`,
    )
    .join('');
  const table = (officers) => `<table class="t">
    <thead><tr><th>${t.thName}</th><th>${t.thRole}</th><th>${dateLabel}</th></tr></thead>
    <tbody>${renderRows(officers)}</tbody></table>`;
  const primary = list.length
    ? table(list)
    : noBoardNote
    ? `<p class="more">${t.noBoard(omitted.length)}</p>`
    : '';
  const more = omitted.length
    ? `<details class="officer-more"><summary>${t.otherRecordedRoles(omitted.length)}</summary>${table(omitted)}</details>`
    : '';
  return `${primary}${more}`;
}

/**
 * The one NIF used for SEO surfaces (title, description, registry heading).
 * Priority: curated seed (human-verified) → registry value → enriched value.
 * Enriched NIFs are externally sourced estimates; the page body already shows
 * them with a caveat, so mirroring them in the snippet is consistent — but
 * they are deliberately NOT asserted as taxID in structured data (see jsonLd).
 */
/** Canonical NIF form for machine surfaces: strip separators, uppercase.
 * Seed NIFs are stored as entered ("A-28004885"); titles, descriptions and
 * taxID must never render the hyphenated variant. */
export function normalizeNif(value) {
  const cleaned = String(value || '').replace(/[^0-9A-Za-z]/g, '').toUpperCase();
  return cleaned || null;
}

export function resolveNif(company, seed) {
  return normalizeNif(
    (seed && seed.nif) || (company && (company.nif || company.enriched_nif)) || null,
  );
}

/** Title + meta description for a company page, CIF-aware when a NIF is known. */
export function buildSeoMeta(
  lang,
  name,
  { nif = null, capital = '', province = '', variant = false, counts = null } = {},
) {
  const t = T[lang] || T.es;
  // The variant needs real numbers to be worth showing. With none of them the
  // headline would read "administradores y socios" — vaguer than the control —
  // so a company with no counts stays on the control template whatever arm it
  // is in. Never ship a variant that is worse than what it replaces.
  const c = counts || {};
  const hasCounts = !!(c.active || c.former || c.filings);
  if (variant && hasCounts) {
    return {
      title: t.titleVariant(name, nif, c),
      desc: t.descVariant(name, capital, province, nif, c),
    };
  }
  return {
    title: t.title(name, nif),
    desc: t.desc(name, capital, province, nif),
  };
}

/**
 * Sole-shareholder lists, dated to the filing that recorded them.
 *
 * A declaration of unipersonalidad is a DATED act, not a standing fact. The
 * page rendered the bare name in the present tense, so a 2019 declaration read
 * as current ownership in 2026 — while `sole_shareholder_declarations` carried
 * the date in the same payload, unused. The graph panel had shown it all along;
 * only the page threw it away.
 *
 * `sole_shareholders_resolved` additionally tracks owners RENAMED since they
 * were declared. Both names are printed: the current one is what the reader
 * needs to follow, the declared one is what BORME actually published, and
 * dropping either breaks traceability back to the filing.
 */
function ownerList(title, names, { declarations = [], resolved = [], lang = 'es', t }) {
  if (!names || !names.length) return '';
  const key = (n) => (n || '').toUpperCase().replace(/[.,]/g, '').replace(/\s+/g, ' ').trim();
  const dateOf = new Map((declarations || [])
    .filter((d) => d && d.name && d.date)
    .map((d) => [key(d.name), d.date]));
  const renameOf = new Map((resolved || [])
    .filter((r) => r && r.current_name)
    .map((r) => [key(r.current_name), r]));

  const items = names.map((name) => {
    const r = renameOf.get(key(name));
    const declaredDate = (r && r.declared_date) || dateOf.get(key(name)) || null;
    const renamed = r && r.declared_name && key(r.declared_name) !== key(name);
    if (!declaredDate) return `<li>${esc(name)}</li>`;
    const when = fmtDate(declaredDate, lang);
    const note = renamed
      ? t.soleDeclaredAs(r.declared_name, when)
      : t.soleDeclaredOn(when);
    return `<li>${esc(name)} <span class="muted">${esc(note)}</span></li>`;
  });
  return `<h3>${esc(title)}</h3><ul class="pill">${items.join('')}</ul>`;
}

function listBlock(title, arr) {
  if (!arr || !arr.length) return '';
  return `<h3>${esc(title)}</h3><ul class="pill">${arr.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
}

