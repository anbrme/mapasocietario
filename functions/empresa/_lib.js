// Length of the always-visible snippet of `full_entry` shown before the reader
// has to expand the <details> to read the rest.
const HISTORY_ENTRY_SNIPPET_LENGTH = 180;

function eventTypeText(value) {
  return typeof value === 'string' ? value : value && value.type ? value.type : '';
}

/**
 * True when the company's FIRST BORME filing is its own incorporation.
 *
 * BORME's digital record starts on 1 Jan 2009, so `first_seen` normally means
 * "the earliest filing we can see", NOT when the company was formed — which is
 * why the fact is labelled defensively and why foundingDate is withheld. When
 * the filing on that date is a Constitución the two genuinely coincide, and it
 * is the one case where the page can say when the company was formed.
 *
 * Events arrive capped (size=100), so an older filing may be missing entirely.
 * Matching on `first_seen` rather than on the earliest event in the list keeps
 * this honest when the list is only a tail: if the opening filing is not there,
 * nothing is claimed.
 */
function firstFilingIsIncorporation(company, events) {
  const firstSeen = String(company?.first_seen || '').slice(0, 10);
  if (!firstSeen) return false;
  return (events || []).some((event) => {
    const date = String(event?.event_date || event?.indexed_date || '').slice(0, 10);
    if (date !== firstSeen) return false;
    return (event?.event_types || []).some((type) => /CONSTITU/i.test(eventTypeText(type)));
  });
}

/**
 * The date BORME recorded the company's dissolution / extinction, read off the
 * filings. The aggregated doc only carries the `is_dissolved` flag; the act
 * itself (has_dissolution, or a lifecycle type "Disolución"/"Extinción") lives
 * in the event log. Newest such filing wins; null when none is in the page's
 * event window (the note then states the fact without a date).
 */
export function dissolutionDateFromEvents(events) {
  const dates = (events || [])
    .filter((event) => {
      if (event?.has_dissolution) return true;
      return (event?.event_types || []).some((type) => /DISOLU|EXTINCI/i.test(eventTypeText(type)));
    })
    .map((event) => String(event?.event_date || event?.indexed_date || '').slice(0, 10))
    .filter((date) => /^\d{4}-\d{2}-\d{2}$/.test(date))
    .sort();
  return dates.length ? dates[dates.length - 1] : null;
}

function eventTypeCategory(value) {
  const type = eventTypeText(value).toUpperCase();
  if (/NOMBR|REELEC/.test(type)) return 'appointments';
  if (/CESE|DIMIS|REVOC/.test(type)) return 'departures';
  if (/CAPITAL/.test(type)) return 'capital';
  if (/SOCIO|UNIPERSONAL|PARTICIPACION|PARTICIPACIÓN/.test(type)) return 'ownership';
  if (/DOMICIL|OBJETO|DENOMIN|ESTATUT|CONSTITU|DISOLU|CONCURSO|TRANSFORM|FUSI|ESCISI/.test(type)) return 'company';
  return 'other';
}

function eventYear(event, t) {
  const match = String(event.event_date || event.indexed_date || '').match(/^(\d{4})/);
  return match ? match[1] : t.historyUnknownYear;
}

// The only host we're willing to link to for a source PDF — a scheme/host
// allowlist, not just HTML-escaping, so a malformed or tampered `pdf_url`
// (e.g. `javascript:...`, or a lookalike host) can never become a live
// anchor. Exported so callers/tests can check it in isolation.
export function isBoeUrl(url) {
  return typeof url === 'string' && url.startsWith('https://www.boe.es/');
}

// The BORME section letter (A, B, ...) embedded in an official PDF filename,
// e.g. ".../BORME-A-2026-162-15.pdf" → "A". Only trusted when the URL itself
// is verified boe.es — an unverified pdf_url's embedded "BORME-X" claim is
// not trusted either.
function bormeSectionLetter(pdfUrl) {
  if (!isBoeUrl(pdfUrl)) return null;
  const match = /BORME-([A-Z])-/.exec(pdfUrl);
  return match ? match[1] : null;
}

// Source line under a card's entry text: a link to the official PDF (only
// when it's verified to be under boe.es) plus the BORME entry number (when
// known, prefixed with its section letter when that's derivable from the
// PDF url). Never renders a dead anchor.
function publicationSourceLine(event, t) {
  const parts = [];
  if (isBoeUrl(event.pdf_url)) {
    parts.push(
      `<a href="${esc(event.pdf_url)}" target="_blank" rel="noopener">${esc(t.historyViewSource)}</a>`,
    );
  }
  if (event.borme_entry_number) {
    const letter = bormeSectionLetter(event.pdf_url);
    parts.push(esc(t.historyEntryNumber(letter, event.borme_entry_number)));
  }
  return parts.length ? `<p class="entry-source">${parts.join(' · ')}</p>` : '';
}

/**
 * Renders one BORME publication card: date, act types, and the registry
 * entry text. Short entries render as plain text; entries longer than the
 * snippet render inside a <details> whose <summary> is the existing ~180
 * char snippet and whose body is the full, escaped, whitespace-preserved
 * text — so the reader can expand without leaving the page. A source line
 * (PDF link + entry number, each shown only when known) follows.
 *
 * Exported so callers/tests can render and assert on a single card.
 */
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Bold the filing's own act labels ("Ceses/Dimisiones.", "Nombramientos.") in
 * already-escaped entry text; only a label at the start or after ". " and
 * followed by its period qualifies, so a name never bolds. */
function boldActLabels(escapedText, eventTypes) {
  const labels = [...new Set((eventTypes || []).map(eventTypeText).filter(Boolean))];
  return labels.reduce(
    (text, label) => text.replace(new RegExp(`(^|\\. )(${escapeRegExp(esc(label))})\\.`, 'g'), '$1<b>$2.</b>'),
    escapedText,
  );
}

export function publicationCard(event, t, lang) {
  const types = (event.event_types || []).map(eventTypeText).filter(Boolean).join(', ');
  const fullEntry = event.full_entry || '';
  const summary = fullEntry.slice(0, HISTORY_ENTRY_SNIPPET_LENGTH);
  const isLong = fullEntry.length > HISTORY_ENTRY_SNIPPET_LENGTH;
  // Expanded, the card shows the full text once (CSS hides the preview) with
  // the act labels in bold, as the BORME itself prints them.
  const entryBody = isLong
    ? `<details class="entry-detail"><summary><span class="entry-preview">${esc(summary)}…</span><span class="entry-toggle" data-closed="${esc(t.historyFullText)}" data-open="${esc(t.historyHideFull)}"></span></summary><p class="entry-full">${boldActLabels(esc(fullEntry), event.event_types)}</p></details>`
    : `<p>${esc(summary)}</p>`;
  return `<li><span class="date">${esc(fmtDate(event.event_date, lang))}</span>
        <strong>${esc(types || t.registryAct)}</strong>
        ${entryBody}${publicationSourceLine(event, t)}</li>`;
}

function eventRows(events, t, lang) {
  return events.map((event) => publicationCard(event, t, lang)).join('');
}

function historyYearCounts(yearEvents) {
  const counts = Object.fromEntries(HISTORY_CATEGORIES.map((category) => [category, 0]));
  yearEvents.forEach((event) => {
    const types = (event.event_types || []).length ? event.event_types : [''];
    types.forEach((type) => { counts[eventTypeCategory(type)] += 1; });
  });
  return counts;
}

// Annual activity matrix: one row per year, one column per change type actually
// present in the data, with explicit counts. Replaces a stacked colour bar that
// made the reader decode segment widths instead of reading numbers.
function eventsHistoryChart(yearGroups, t) {
  const series = yearGroups.map(([year, yearEvents]) => {
    const counts = historyYearCounts(yearEvents);
    return { year, counts, total: Object.values(counts).reduce((sum, count) => sum + count, 0) };
  });
  const usedCategories = HISTORY_CATEGORIES.filter((category) =>
    series.some((year) => year.counts[category] > 0),
  );
  if (!usedCategories.length) return '';
  const h = t.historyMatrixHeaders;
  const cell = (count, label) =>
    count > 0
      ? `<td class="history-count" data-label="${esc(label)}">${count}</td>`
      : '<td class="history-zero">—</td>';
  const headCells = usedCategories
    .map((category) => `<th scope="col" title="${esc(t.historyChangeTypes[category])}"><i class="history-swatch history-${category}"></i>${esc(h[category])}</th>`)
    .join('');
  const rows = series
    .map(({ year, counts, total }) =>
      `<tr><th scope="row">${esc(year)}</th>${usedCategories.map((category) => cell(counts[category], h[category])).join('')}<td class="history-total" data-label="${esc(h.total)}">${total}</td></tr>`,
    )
    .join('');
  const totals = usedCategories.map((category) =>
    series.reduce((sum, year) => sum + year.counts[category], 0),
  );
  const grandTotal = totals.reduce((sum, count) => sum + count, 0);
  const footer = series.length > 1
    ? `<tfoot><tr><th scope="row">${esc(h.total)}</th>${totals.map((count, index) => cell(count, h[usedCategories[index]])).join('')}<td class="history-total" data-label="${esc(h.total)}">${grandTotal}</td></tr></tfoot>`
    : '';
  return `<div class="history-chart">
    <h3>${t.historyChartTitle}</h3>
    <div class="history-matrix-wrap"><table class="history-matrix">
      <thead><tr><th scope="col">${esc(h.year)}</th>${headCells}<th scope="col">${esc(h.total)}</th></tr></thead>
      <tbody>${rows}</tbody>
      ${footer}
    </table></div>
    <p class="more">${t.historyChartNote}</p>
  </div>`;
}

export function eventsBlock(events, t, lang, totalPublications = null) {
  if (!events || !events.length) return '';
  const sortedEvents = [...events].sort((a, b) =>
    String(b.event_date || b.indexed_date || '').localeCompare(String(a.event_date || a.indexed_date || '')),
  );
  const groups = new Map();
  sortedEvents.forEach((event) => {
    const year = eventYear(event, t);
    if (!groups.has(year)) groups.set(year, []);
    groups.get(year).push(event);
  });
  const yearGroups = Array.from(groups.entries());
  const years = yearGroups
    .map(([year, yearEvents], yearIndex) => {
      const batches = [];
      for (let index = 0; index < yearEvents.length; index += HISTORY_BATCH_SIZE) {
        batches.push(yearEvents.slice(index, index + HISTORY_BATCH_SIZE));
      }
      const firstBatch = `<ol class="timeline">${eventRows(batches[0], t, lang)}</ol>`;
      const remainingBatches = batches
        .slice(1)
        .map((batch, batchIndex) => {
          const from = (batchIndex + 1) * HISTORY_BATCH_SIZE + 1;
          const to = from + batch.length - 1;
          return `<details class="history-batch"><summary>${t.historyBatch(from, to)}</summary><ol class="timeline">${eventRows(batch, t, lang)}</ol></details>`;
        })
        .join('');
      return `<details class="history-year"${yearIndex === 0 ? ' open' : ''}>
        <summary>${t.historyYear(year, yearEvents.length)}</summary>
        ${firstBatch}${remainingBatches}
      </details>`;
    })
    .join('');
  const parsedTotal = Number(totalPublications);
  const total = Number.isFinite(parsedTotal) && parsedTotal > sortedEvents.length
    ? parsedTotal
    : sortedEvents.length;
  return `<section class="history"><h2>${t.recentHistory}</h2>
    <p class="more">${t.historyIntro(sortedEvents.length, total)}</p>
    ${eventsHistoryChart(yearGroups, t)}
    <div class="history-years">${years}</div>
  </section>`;
}

function jsonLd(company, slug, lang, t, seed, isIncorporation = false, { dissolutionDate = null } = {}) {
  // A dissolved company employs nobody; its open seats are history, not staff.
  const officers = company.is_dissolved
    ? []
    : (company.officers_active || []).map((o) => o.name || o.name_normalized).filter(Boolean);

  // Identifiers: for curated IBEX companies use the verified NIF/LEI/ISIN from the
  // seed \u2014 stable, globally-unique business identifiers \u2014 as schema.org PropertyValue.
  // The old `(company.identifiers || []).join(', ')` was a comma-joined blob of ~400
  // BORME entry IDs, which reset yearly and aren't a real identifier; it's dropped.
  const identifier = [];
  // Structured data asserts facts without the page's "external estimate" caveat,
  // so only verified NIFs (curated seed or registry-sourced) become taxID /
  // identifier here — enriched_nif stays out even though the snippet shows it.
  const verifiedNif = normalizeNif((seed && seed.nif) || company.nif || null);
  if (verifiedNif) identifier.push({ '@type': 'PropertyValue', propertyID: 'NIF', value: verifiedNif });
  if (seed) {
    if (seed.lei) identifier.push({ '@type': 'PropertyValue', propertyID: 'LEI', value: seed.lei });
    if (seed.isin) identifier.push({ '@type': 'PropertyValue', propertyID: 'ISIN', value: seed.isin });
  }

  // sameAs binds this page to the real-world entity (official site) for the Knowledge Graph.
  const sameAs = seed && seed.website ? [seed.website] : [];

  const org = {
    '@context': 'https://schema.org',
    // Corporation (an Organization subtype) supports tickerSymbol for listed companies.
    '@type': seed ? 'Corporation' : 'Organization',
    name: company.company_name,
    url: companyUrl(lang, slug),
    ...(seed && seed.ticker ? { tickerSymbol: seed.ticker } : {}),
    ...(verifiedNif ? { taxID: verifiedNif } : {}),
    ...(company.current_address ? { address: company.current_address } : {}),
    ...(company.province ? { areaServed: company.province } : {}),
    ...(officers.length ? { employee: officers.slice(0, 10).map((n) => ({ '@type': 'Person', name: n })) } : {}),
    ...(identifier.length ? { identifier } : {}),
    ...(sameAs.length ? { sameAs } : {}),
    ...(isIncorporation && company.first_seen
      ? { foundingDate: String(company.first_seen).slice(0, 10) }
      : {}),
    ...(dissolutionDate ? { dissolutionDate } : {}),
    description: t.jsonLdDesc(company.company_name),
  };
  // foundingDate is emitted ONLY when the first BORME filing is the company's own
  // Constituci\u00f3n. Otherwise the only date available is company.first_seen (first
  // BORME appearance), which is not the incorporation date \u2014 wrong data is worse
  // than none.

  // BreadcrumbList mirrors the visible breadcrumb (Home \u203a Empresas \u203a Name) at the
  // bottom of the page; Google requires the structured trail to match the on-page one.
  const breadcrumb = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: t.home, item: `${SITE}/` },
      { '@type': 'ListItem', position: 2, name: t.crumbCompanies, item: `${SITE}/app/` },
      { '@type': 'ListItem', position: 3, name: company.company_name },
    ],
  };

  // Site-level publisher node \u2014 binds the PAGE (not the described company) to the
  // Nurnberg brand/org. The company `org` node above stays free of any Nurnberg link.
  const site = {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    '@id': 'https://mapasocietario.es/#website',
    url: `${SITE}/`,
    name: 'Mapa Societario',
    publisher: { '@id': 'https://nurnbergconsulting.com/#org' },
    about: { '@id': 'https://mapasocietario.es/#brand' },
  };

  const serialize = (obj) => JSON.stringify(obj)
    .replace(/</g, '\\u003c')
    .replace(/-->/g, '--\\u003e')
    .replace(/[\u2028\u2029]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
  return [org, breadcrumb, site]
    .map((obj) => `<script type="application/ld+json">${serialize(obj)}</script>`)
    .join('');
}

